foreach ($relPath in $map.Keys) {
    if (-not (Test-Path $relPath)) {
        Write-Warning "File not found: $relPath"
        continue
    }

    $seo = $map[$relPath]
    $title = $seo.title
    $desc = $seo.desc
    $content = [System.IO.File]::ReadAllText($relPath, [System.Text.Encoding]::UTF8)

    # 1. Replace or insert <title>
    if ($content -match '<title[^>]*>.*?</title>') {
        $content = [regex]::Replace($content, '<title[^>]*>.*?</title>', "<title>$title</title>")
    } else {
        $content = [regex]::Replace($content, '(<head\b[^>]*>)', "`$1`n    <title>$title</title>")
    }

    # 2. Meta name="title"
    if ($content -match '<meta\s+[^>]*name="title"[^>]*>') {
        $content = [regex]::Replace($content, '<meta\s+[^>]*name="title"[^>]*>', "<meta name=""title"" content=""$title""/>")
    } elseif ($content -match '<meta\s+[^>]*content="[^"]*"\s+name="title"[^>]*>') {
        $content = [regex]::Replace($content, '<meta\s+[^>]*content="[^"]*"\s+name="title"[^>]*>', "<meta name=""title"" content=""$title""/>")
    }

    # 3. Meta name="description"
    if ($content -match '<meta\s+[^>]*name="description"[^>]*>') {
        $content = [regex]::Replace($content, '<meta\s+[^>]*name="description"[^>]*>', "<meta name=""description"" content=""$desc""/>")
    } elseif ($content -match '<meta\s+[^>]*content="[^"]*"\s+name="description"[^>]*>') {
        $content = [regex]::Replace($content, '<meta\s+[^>]*content="[^"]*"\s+name="description"[^>]*>', "<meta name=""description"" content=""$desc""/>")
    } else {
        $content = [regex]::Replace($content, '(<title[^>]*>.*?</title>)', "`$1`n    <meta name=""description"" content=""$desc""/>")
    }

    # 4. OpenGraph title & desc
    if ($content -match '<meta\s+[^>]*property="og:title"[^>]*>') {
        $content = [regex]::Replace($content, '<meta\s+[^>]*property="og:title"[^>]*>', "<meta property=""og:title"" content=""$title""/>")
    }
    if ($content -match '<meta\s+[^>]*property="og:description"[^>]*>') {
        $content = [regex]::Replace($content, '<meta\s+[^>]*property="og:description"[^>]*>', "<meta property=""og:description"" content=""$desc""/>")
    }

    # 5. Twitter title & desc
    if ($content -match '<meta\s+[^>]*name="twitter:title"[^>]*>') {
        $content = [regex]::Replace($content, '<meta\s+[^>]*name="twitter:title"[^>]*>', "<meta name=""twitter:title"" content=""$title""/>")
    }
    if ($content -match '<meta\s+[^>]*name="twitter:description"[^>]*>') {
        $content = [regex]::Replace($content, '<meta\s+[^>]*name="twitter:description"[^>]*>', "<meta name=""twitter:description"" content=""$desc""/>")
    }

    [System.IO.File]::WriteAllText($relPath, $content, [System.Text.Encoding]::UTF8)
    Write-Host "Updated core page: $relPath"
}

